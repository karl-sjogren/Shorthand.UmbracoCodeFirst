using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Shorthand.UmbracoCodeFirst.InternalSourceGenerators;

[Generator]
public sealed class UmbracoIconGenerator : IIncrementalGenerator {
    private const string _fileName = "umbraco-icons.json";

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var metadata = context.AdditionalTextsProvider
            .Where(static text => text.Path.EndsWith(_fileName, StringComparison.OrdinalIgnoreCase))
            .Select(static (text, cancellationToken) => Parse(text, cancellationToken));

        context.RegisterSourceOutput(
            context.CompilationProvider.Combine(metadata.Collect()),
            static (productionContext, input) => {
                if(input.Left.GetTypeByMetadataName("Shorthand.UmbracoCodeFirst.UmbracoIcons") is not null) {
                    return;
                }

                var result = input.Right.FirstOrDefault();
                if(result is not null) {
                    Emit(productionContext, result);
                }
            });
    }

    private static IconCatalogResult Parse(AdditionalText text, CancellationToken cancellationToken) {
        var content = text.GetText(cancellationToken)?.ToString() ?? string.Empty;
        if(content.Length == 0) {
            return IconCatalogResult.Failure("The icon catalog file is empty.");
        }

        try {
            using var document = JsonDocument.Parse(content);
            if(!document.RootElement.TryGetProperty("icons", out var icons)
                || icons.ValueKind != JsonValueKind.Array) {
                return IconCatalogResult.Failure("The icon catalog file must contain an 'icons' array.");
            }

            var entries = icons
                .EnumerateArray()
                .Select(static icon => icon.ValueKind == JsonValueKind.String ? icon.GetString() : null)
                .ToArray();
            if(entries.Any(static icon => string.IsNullOrWhiteSpace(icon))) {
                return IconCatalogResult.Failure("Every icon catalog entry must be a non-empty string.");
            }

            var duplicate = entries
                .GroupBy(static icon => icon!, StringComparer.Ordinal)
                .FirstOrDefault(static group => group.Count() > 1);
            if(duplicate is not null) {
                return IconCatalogResult.Failure($"The icon '{duplicate.Key}' is duplicated.");
            }

            var iconsWithIdentifiers = entries
                .Select(static icon => new IconMetadata(icon!, ToIdentifier(icon!)))
                .ToArray();
            var invalid = iconsWithIdentifiers.FirstOrDefault(static icon => icon.Identifier is null);
            if(invalid is not null) {
                return IconCatalogResult.Failure(
                    $"The icon '{invalid.Name}' cannot be converted to a C# identifier.");
            }

            var identifierCollision = iconsWithIdentifiers
                .GroupBy(static icon => icon.Identifier!, StringComparer.Ordinal)
                .FirstOrDefault(static group => group.Count() > 1);
            if(identifierCollision is not null) {
                return IconCatalogResult.Failure(
                    $"The icons '{string.Join("', '", identifierCollision.Select(static icon => icon.Name))}' "
                    + $"all generate the identifier '{identifierCollision.Key}'.");
            }

            return IconCatalogResult.Success(iconsWithIdentifiers
                .OrderBy(static icon => icon.Name, StringComparer.Ordinal)
                .ToArray());
        } catch(JsonException exception) {
            return IconCatalogResult.Failure($"The icon catalog file is invalid JSON: {exception.Message}");
        }
    }

    private static void Emit(SourceProductionContext context, IconCatalogResult result) {
        if(!result.IsValid) {
            context.ReportDiagnostic(Diagnostic.Create(
                new DiagnosticDescriptor(
                    "UCF201",
                    "Invalid Umbraco icon catalog",
                    "{0}",
                    "CodeFirst",
                    DiagnosticSeverity.Error,
                    isEnabledByDefault: true),
                Location.None,
                result.Error));
            return;
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Shorthand.UmbracoCodeFirst;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>");
        builder.AppendLine("/// Constants for the built-in Umbraco icons.");
        builder.AppendLine("/// </summary>");
        builder.AppendLine("public static class UmbracoIcons {");

        foreach(var icon in result.Entries!) {
            builder.Append("    /// <summary>Umbraco icon '");
            builder.Append(EscapeXml(icon.Name));
            builder.AppendLine("'.</summary>");
            builder.Append("    public const string ");
            builder.Append(icon.Identifier);
            builder.Append(" = \"");
            builder.Append(EscapeString(icon.Name));
            builder.AppendLine("\";");
            builder.AppendLine();
        }

        builder.AppendLine("}");
        context.AddSource("UmbracoIcons.g.cs", builder.ToString());
    }

    private static string? ToIdentifier(string iconName) {
        var name = iconName.StartsWith("icon-", StringComparison.Ordinal)
            ? iconName.Substring(5)
            : iconName;
        var builder = new StringBuilder();
        var capitalize = true;

        foreach(var character in name) {
            if(!char.IsLetterOrDigit(character)) {
                capitalize = true;
                continue;
            }

            if(builder.Length == 0 && char.IsDigit(character)) {
                builder.Append("Icon");
            }

            builder.Append(capitalize
                ? char.ToUpperInvariant(character)
                : character);
            capitalize = false;
        }

        if(builder.Length == 0) {
            return null;
        }

        var identifier = builder.ToString();
        return SyntaxFacts.GetKeywordKind(identifier) == SyntaxKind.None
            ? identifier
            : $"Icon{identifier}";
    }

    private static string EscapeString(string value) =>
        value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string EscapeXml(string value) =>
        value.Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");

    private sealed class IconMetadata {
        public IconMetadata(string name, string? identifier) {
            Name = name;
            Identifier = identifier;
        }

        public string Name { get; }
        public string? Identifier { get; }
    }

    private sealed class IconCatalogResult {
        private IconCatalogResult(bool isValid, IReadOnlyList<IconMetadata>? entries, string? error) {
            IsValid = isValid;
            Entries = entries;
            Error = error;
        }

        public bool IsValid { get; }
        public IReadOnlyList<IconMetadata>? Entries { get; }
        public string? Error { get; }

        public static IconCatalogResult Success(IReadOnlyList<IconMetadata> entries) =>
            new(true, entries, null);

        public static IconCatalogResult Failure(string error) =>
            new(false, null, error);
    }
}
