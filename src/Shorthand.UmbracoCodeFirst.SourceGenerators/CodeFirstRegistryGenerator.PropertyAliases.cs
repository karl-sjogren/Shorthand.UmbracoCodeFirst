using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

#pragma warning disable IDE0055

namespace Shorthand.UmbracoCodeFirst.SourceGenerators;

public sealed partial class CodeFirstRegistryGenerator {
#pragma warning disable RS2008
    private static readonly DiagnosticDescriptor _propertyAliasesConflict = new(
        "UCF116",
        "Property alias constants conflict",
        "Cannot generate property aliases for '{0}' because it already declares a member named 'PropertyAliases'",
        "CodeFirst",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor _unresolvedPropertyAlias = new(
        "UCF117",
        "Unresolved generated property alias",
        "Generated property alias '{0}' cannot be used in a code-first attribute in the same compilation; use a string constant or reference a compiled model",
        "CodeFirst",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor _unsupportedPropertyAliasContainer = new(
        "UCF118",
        "Cannot generate property aliases",
        "Cannot generate property aliases for '{0}': its containing types must be partial and it cannot be file-local",
        "CodeFirst",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);
#pragma warning restore RS2008

    private static void EmitOtherPropertyAliases(
        SourceProductionContext context,
        ImmutableArray<INamedTypeSymbol> definitions) {
        foreach(var definition in definitions) {
            if(FindContentTypeAttribute(definition) is null || FindDocumentTypeAttribute(definition) is not null
                || !definition.GetMembers().OfType<IPropertySymbol>()
                    .Any(static property => FindAttribute(property, _propertyAttributeMetadataName) is not null)) {
                continue;
            }

            var containers = new Stack<INamedTypeSymbol>();
            for(var current = definition; current is not null; current = current.ContainingType) {
                containers.Push(current);
            }

            if(containers.Any(static type => !CanExtendPartialType(type))) {
                context.ReportDiagnostic(Diagnostic.Create(
                    _unsupportedPropertyAliasContainer,
                    definition.Locations.FirstOrDefault(),
                    definition.ToDisplayString()));
                continue;
            }

            var builder = new IndentedStringBuilder();
            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("#nullable enable");
            if(!definition.ContainingNamespace.IsGlobalNamespace) {
                builder.Append("namespace ");
                builder.Append(definition.ContainingNamespace.ToDisplayString());
                builder.AppendLine(";");
            }

            foreach(var container in containers) {
                AppendPartialTypeDeclaration(builder, container);
                builder.Indent++;
            }

            AppendPropertyAliases(builder, definition, context);
            foreach(var _ in containers) {
                builder.Indent--;
                builder.AppendLine("}");
            }

            context.AddSource(
                $"{SanitizeHintName(definition.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))}.PropertyAliases.g.cs",
                builder.ToString());
        }
    }

    private static void AppendPropertyAliases(
        IndentedStringBuilder builder,
        INamedTypeSymbol definition,
        SourceProductionContext context) {
        var properties = definition.GetMembers().OfType<IPropertySymbol>()
            .Where(static property => FindAttribute(property, _propertyAttributeMetadataName) is not null)
            .OrderBy(static property => property.Name, StringComparer.Ordinal)
            .ToArray();
        if(properties.Length == 0) {
            return;
        }

        if(definition.Name == "PropertyAliases" || definition.GetMembers("PropertyAliases").Length != 0) {
            context.ReportDiagnostic(Diagnostic.Create(
                _propertyAliasesConflict,
                definition.GetMembers("PropertyAliases").FirstOrDefault()?.Locations.FirstOrDefault()
                    ?? definition.Locations.FirstOrDefault(),
                definition.ToDisplayString()));
            return;
        }

        AppendGeneratedCodeAttribute(builder, fullyQualified: true);
        builder.AppendLine(HasInheritedPropertyAliases(definition)
            ? "public new static class PropertyAliases {"
            : "public static class PropertyAliases {");
        builder.Indent++;
        foreach(var property in properties) {
            var attribute = FindAttribute(property, _propertyAttributeMetadataName)!;
            var (_, alias) = GetPropertyMetadata(attribute, FindAttributeSyntax(property, _propertyAttributeMetadataName));
            builder.Append("public const string ");
            builder.Append(EscapeIdentifier(property.Name));
            builder.Append(" = ");
            builder.Append(SymbolDisplay.FormatLiteral(alias, true));
            builder.AppendLine(";");
        }

        builder.Indent--;
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static string EscapeIdentifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? $"@{name}" : name;

    private static bool CanExtendPartialType(INamedTypeSymbol type) =>
        type.DeclaringSyntaxReferences
            .Select(static reference => reference.GetSyntax())
            .OfType<TypeDeclarationSyntax>()
            .Any(static declaration => declaration.Modifiers.Any(SyntaxKind.PartialKeyword)
                && !declaration.Modifiers.Any(SyntaxKind.FileKeyword));

    private static void AppendPartialTypeDeclaration(IndentedStringBuilder builder, INamedTypeSymbol type) {
        builder.Append(type.IsRecord
            ? type.TypeKind == TypeKind.Struct ? "partial record struct " : "partial record class "
            : type.TypeKind switch {
                TypeKind.Struct => "partial struct ",
                TypeKind.Interface => "partial interface ",
                _ => "partial class ",
            });
        builder.Append(EscapeIdentifier(type.Name));
        if(type.TypeParameters.Length > 0) {
            builder.Append("<");
            builder.Append(string.Join(", ", type.TypeParameters.Select(static parameter =>
                (parameter.Variance == VarianceKind.In ? "in " : parameter.Variance == VarianceKind.Out ? "out " : string.Empty)
                + EscapeIdentifier(parameter.Name))));
            builder.Append(">");
        }

        builder.AppendLine(" {");
    }

    private static bool HasInheritedPropertyAliases(INamedTypeSymbol definition) {
        for(var baseType = definition.BaseType; baseType is not null; baseType = baseType.BaseType) {
            if(baseType.GetMembers("PropertyAliases").Any(static member => member.DeclaredAccessibility != Accessibility.Private)
                || (FindContentTypeAttribute(baseType) is not null
                    && baseType.GetMembers().OfType<IPropertySymbol>()
                        .Any(static property => FindAttribute(property, _propertyAttributeMetadataName) is not null))) {
                return true;
            }
        }

        return false;
    }

    private static void ReportUnresolvedPropertyAliasArguments(
        SourceProductionContext context,
        ImmutableArray<INamedTypeSymbol> definitions,
        Compilation compilation) {
        foreach(var definition in definitions) {
            foreach(var symbol in new[] { (ISymbol)definition }.Concat(definition.GetMembers())) {
                foreach(var attribute in symbol.GetAttributes()) {
                    if(!IsCodeFirstAttribute(attribute.AttributeClass)
                        || attribute.ApplicationSyntaxReference?.GetSyntax(context.CancellationToken) is not AttributeSyntax syntax
                        || syntax.ArgumentList is null) {
                        continue;
                    }

                    var semanticModel = compilation.GetSemanticModel(syntax.SyntaxTree);
                    foreach(var access in syntax.ArgumentList.DescendantNodes().OfType<MemberAccessExpressionSyntax>()) {
                        var isAliasContainer = access.Expression switch {
                            MemberAccessExpressionSyntax container => container.Name.Identifier.ValueText == "PropertyAliases",
                            IdentifierNameSyntax container => container.Identifier.ValueText == "PropertyAliases",
                            _ => false,
                        };
                        if(!isAliasContainer
                            || semanticModel.GetConstantValue(access, context.CancellationToken).HasValue) {
                            continue;
                        }

                        context.ReportDiagnostic(Diagnostic.Create(
                            _unresolvedPropertyAlias, access.GetLocation(), access.ToString()));
                    }
                }
            }
        }
    }

    private static bool IsCodeFirstAttribute(INamedTypeSymbol? attributeType) {
        for(var current = attributeType; current is not null; current = current.BaseType) {
            if(current.ContainingNamespace.ToDisplayString() == "Shorthand.UmbracoCodeFirst.Attributes"
                && current.Name.StartsWith("UCF", StringComparison.Ordinal)) {
                return true;
            }
        }

        return false;
    }
}
