using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Shorthand.UmbracoCodeFirst.SourceGenerators;

public sealed partial class CodeFirstRegistryGenerator {
    private sealed class CapturedSource(string fileName, string content, INamedTypeSymbol? definition) {
        public string FileName { get; } = fileName;
        public string Content { get; } = content;
        public INamedTypeSymbol? Definition { get; } = definition;
    }

    private static void AddGeneratedSource(
        SourceProductionContext context,
        string fileName,
        string content,
        List<CapturedSource>? capturedSources,
        INamedTypeSymbol? definition = null) {
        context.AddSource(fileName, content);
        capturedSources?.Add(new CapturedSource(fileName, content, definition));
    }

    private static void EmitSourceCatalog(
        SourceProductionContext context,
        ImmutableArray<INamedTypeSymbol> definitions,
        IReadOnlyList<TemplateDefinition> templates,
        IReadOnlyList<CapturedSource> sources) {
        var trees = new Dictionary<SyntaxTree, HashSet<int>>();
        for(var index = 0; index < definitions.Length; index++) {
            foreach(var declaration in definitions[index].DeclaringSyntaxReferences) {
                if(!trees.TryGetValue(declaration.SyntaxTree, out var indices)) {
                    indices = [];
                    trees.Add(declaration.SyntaxTree, indices);
                }

                indices.Add(index);
            }
        }

        var originals = new List<(string FileName, string Content, HashSet<int> Indices)>();
        var fileNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach(var entry in trees.OrderBy(item => item.Key.FilePath, StringComparer.Ordinal)) {
            var tree = entry.Key;
            var fileName = Path.GetFileName(tree.FilePath);
            if(string.IsNullOrEmpty(fileName)) {
                fileName = "Source.cs";
            }

            var baseName = fileName;
            var count = 2;
            while(!fileNames.Add(fileName)) {
                fileName = $"{Path.GetFileNameWithoutExtension(baseName)} ({count++}){Path.GetExtension(baseName)}";
            }

            originals.Add((fileName, tree.GetText(context.CancellationToken).ToString(), entry.Value));
        }

        for(var index = 0; index < templates.Count; index++) {
            originals.Add((templates[index].FileName, templates[index].Content, [definitions.Length + index]));
        }

        var builder = new IndentedStringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("namespace Shorthand.UmbracoCodeFirst.Generated;");
        builder.AppendLine("public sealed class GeneratedCodeFirstSourceCatalog : global::Shorthand.UmbracoCodeFirst.Metadata.ICodeFirstGeneratedSourceCatalog {");
        builder.Indent++;
        for(var index = 0; index < sources.Count; index++) {
            builder.Append("private static readonly global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstGeneratedSource File");
            builder.Append(index.ToString(System.Globalization.CultureInfo.InvariantCulture));
            builder.Append(" = new(");
            builder.Append(SymbolDisplay.FormatLiteral(sources[index].FileName, true));
            builder.Append(", ");
            builder.Append(SymbolDisplay.FormatLiteral(sources[index].Content, true));
            builder.AppendLine(");");
        }

        for(var index = 0; index < originals.Count; index++) {
            builder.Append("private static readonly global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstGeneratedSource Original");
            builder.Append(index.ToString(System.Globalization.CultureInfo.InvariantCulture));
            builder.Append(" = new(");
            builder.Append(SymbolDisplay.FormatLiteral(originals[index].FileName, true));
            builder.Append(", ");
            builder.Append(SymbolDisplay.FormatLiteral(originals[index].Content, true));
            builder.AppendLine(") { IsOriginal = true };");
        }

        builder.AppendLine("public global::System.Collections.Generic.IReadOnlyList<global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstGeneratedSource> GetSources(int definitionIndex) => definitionIndex switch {");
        builder.Indent++;
        for(var index = 0; index < definitions.Length + templates.Count; index++) {
            builder.Append(index.ToString(System.Globalization.CultureInfo.InvariantCulture));
            builder.Append(" => [");
            var fileIndexes = Enumerable.Range(0, sources.Count)
                .Where(sourceIndex =>
                    sources[sourceIndex].FileName == "CodeFirstRegistry.g.cs"
                    || (index >= definitions.Length && sources[sourceIndex].FileName == "UmbracoTemplates.g.cs")
                    || (index < definitions.Length && SymbolEqualityComparer.Default.Equals(
                        sources[sourceIndex].Definition, definitions[index])))
                .OrderBy(sourceIndex => sources[sourceIndex].FileName == "CodeFirstRegistry.g.cs" ? 1 : 0);
            var originalIndexes = Enumerable.Range(0, originals.Count).Where(originalIndex => originals[originalIndex].Indices.Contains(index));
            builder.Append(string.Join(", ", fileIndexes.Select(static fileIndex =>
                $"File{fileIndex.ToString(System.Globalization.CultureInfo.InvariantCulture)}")
                .Concat(originalIndexes.Select(static originalIndex =>
                    $"Original{originalIndex.ToString(System.Globalization.CultureInfo.InvariantCulture)}"))));
            builder.AppendLine("],");
        }

        builder.AppendLine("_ => [],");
        builder.Indent--;
        builder.AppendLine("};");
        builder.Indent--;
        builder.AppendLine("}");
        context.AddSource("CodeFirstSourceCatalog.g.cs", builder.ToString());
    }
}
