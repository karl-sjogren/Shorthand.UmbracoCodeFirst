    private static readonly DiagnosticDescriptor _unresolvedAllowedChild = new(
        "UCF113",
        "Unresolved allowed child alias",
        "Allowed child alias expression '{0}' on '{1}' could not be resolved; use a string constant or a generated document type's ModelTypeAlias",
        "CodeFirst",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor _invalidCollectionConfiguration = new(
        "UCF114",
        "Invalid collection configuration",
        "Collection on '{0}' requires a document or media type and a concrete CodeFirstCollectionConfiguration with a public parameterless constructor",
        "CodeFirst",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor _invalidPropertyDataType = new(
        "UCF123",
        "Invalid property data type reference",
        "Property '{0}' must specify exactly one data type alias or a valid non-empty GUID data type key",
        "CodeFirst",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static void EmitRegistry(
        SourceProductionContext context,
        ImmutableArray<INamedTypeSymbol> definitionSymbols,
        Compilation compilation,
        Compilation templateCompilation,
        IReadOnlyList<TemplateDefinition> templates,
        List<CapturedSource>? capturedSources) {
        IEnumerable<INamedTypeSymbol> definitions = definitionSymbols
            .OrderBy(static symbol => symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), StringComparer.Ordinal);

        var builder = new IndentedStringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Shorthand.UmbracoCodeFirst.Generated;");
        builder.AppendLine();
        AppendGeneratedCodeAttribute(builder, fullyQualified: true);
        builder.AppendLine("public sealed class GeneratedCodeFirstDefinitionRegistry : global::Shorthand.UmbracoCodeFirst.Metadata.ICodeFirstDefinitionRegistry {");
        builder.Indent++;
        builder.Append("public global::System.Collections.Generic.IReadOnlyList<global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinition> ");
        builder.AppendLine("Definitions { get; } = [");
        builder.Indent++;

        var dataTypeAliases = BuildDataTypeAliasMap(definitionSymbols);
        foreach (var definition in definitions) {
            AppendDefinition(builder, definition, compilation, templateCompilation, definitionSymbols, dataTypeAliases, context);
        }

        foreach(var template in templates) {
            builder.Append("new global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinition(");
            builder.Append("global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinitionKind.Template, ");
            builder.Append(SymbolDisplay.FormatLiteral(template.Alias, true));
            builder.Append(", ");
            builder.Append(SymbolDisplay.FormatLiteral(template.Name, true));
            builder.Append(", null, [], TemplateContentHash: ");
            builder.Append(SymbolDisplay.FormatLiteral(template.ContentHash, true));
            builder.AppendLine("),");
        }

        builder.Indent--;
        builder.AppendLine("];");
        builder.Indent--;
        builder.AppendLine("}");

        AddGeneratedSource(context, "CodeFirstRegistry.g.cs", builder.ToString(), capturedSources);
    }

    private static void AppendDefinition(
        IndentedStringBuilder builder,
        INamedTypeSymbol definition,
        Compilation compilation,
        Compilation templateCompilation,
        ImmutableArray<INamedTypeSymbol> definitionSymbols,
        IReadOnlyDictionary<string, string> dataTypeAliases,
        SourceProductionContext context) {
        var contentTypeAttribute = FindContentTypeAttribute(definition);
        if (contentTypeAttribute is not null) {
            var name = GetNameArgument(contentTypeAttribute);
            var alias = GetAliasArgument(contentTypeAttribute, name);
            var kind = IsAttribute(contentTypeAttribute, _mediaTypeAttributeMetadataName)
                ? "MediaType"
                : IsAttribute(contentTypeAttribute, _memberTypeAttributeMetadataName)
                    ? "MemberType"
                    : "DocumentType";
            builder.Append("new global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinition(");
            builder.Append("global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinitionKind.");
            builder.Append(kind);
            builder.Append(", ");
            builder.Append(
                SymbolDisplay.FormatLiteral(alias, true));
            builder.Append(", ");
            builder.Append(
                SymbolDisplay.FormatLiteral(name, true));
            builder.AppendLine(", null, [");
            builder.Indent++;

            foreach (var property in definition.GetMembers().OfType<IPropertySymbol>()) {
                var propertyAttribute = property.GetAttributes().FirstOrDefault(
                    attribute => IsAttribute(attribute, _propertyAttributeMetadataName));
                if (propertyAttribute is null) {
                    continue;
                }

                propertyAttribute = GetReboundAttribute(propertyAttribute, templateCompilation);
                var propertySyntax = FindAttributeSyntax(property, _propertyAttributeMetadataName);
                var (propertyName, propertyAlias) = GetPropertyMetadata(propertyAttribute, propertySyntax);
                var dataTypeAlias = GetDataTypeArgument(propertyAttribute, dataTypeAliases, propertySyntax);
                var dataTypeKey = GetNamedStringArgument(propertyAttribute, "DataTypeKey");
                var hasDataTypeKey = propertyAttribute.NamedArguments.Any(static argument => argument.Key == "DataTypeKey");
                if((!hasDataTypeKey && string.IsNullOrWhiteSpace(dataTypeAlias))
                    || (hasDataTypeKey && (!string.IsNullOrWhiteSpace(dataTypeAlias)
                        || !Guid.TryParse(dataTypeKey, out var key) || key == Guid.Empty))) {
                    context.ReportDiagnostic(Diagnostic.Create(
                        _invalidPropertyDataType,
                        propertySyntax?.GetLocation() ?? property.Locations.FirstOrDefault(),
                        property.Name));
                }

                var descriptionAttribute = FindAttribute(property, _descriptionAttributeMetadataName);
                var groupAttribute = FindLayoutAttribute(property, _groupAttributeMetadataName);
                var groupMetadata = GetLayoutMetadata(groupAttribute, compilation);
                var tabAttribute = FindLayoutAttribute(property, _tabAttributeMetadataName);
                var tabMetadata = GetLayoutMetadata(tabAttribute, compilation);
                var validationAttribute = FindValidationAttribute(property);
                var validationMetadata = GetValidationMetadata(validationAttribute, compilation);
                builder.Append("new global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstPropertyDefinition(");
                builder.Append(
                    SymbolDisplay.FormatLiteral(propertyAlias, true));
                builder.Append(", ");
                builder.Append(
                    SymbolDisplay.FormatLiteral(propertyName, true));
                builder.Append(", ");
                builder.Append(
                    SymbolDisplay.FormatLiteral(
                        dataTypeAlias,
                        true));
                builder.Append(", ");
                builder.Append(GetConstructorStringLiteral(descriptionAttribute));
                builder.Append(", ");
                builder.Append(groupMetadata is null
                    ? "null"
                    : SymbolDisplay.FormatLiteral(groupMetadata.Alias, true));
                builder.Append(", ");
                builder.Append(groupMetadata is null
                    ? "null"
                    : SymbolDisplay.FormatLiteral(groupMetadata.Name, true));
                builder.Append(", ");
                builder.Append((groupMetadata?.SortOrder ?? 0).ToString());
                builder.Append(", ");
                builder.Append(tabMetadata is null
                    ? "null"
                    : SymbolDisplay.FormatLiteral(tabMetadata.Alias, true));
                builder.Append(", ");
                builder.Append(tabMetadata is null
                    ? "null"
                    : SymbolDisplay.FormatLiteral(tabMetadata.Name, true));
                builder.Append(", ");
                builder.Append((tabMetadata?.SortOrder ?? 0).ToString());
                builder.Append(", ");
                builder.Append(GetNamedIntArgument(propertyAttribute, "SortOrder").ToString());
                builder.Append(", ");
                builder.Append(GetNamedBoolArgument(propertyAttribute, "Mandatory").ToString().ToLowerInvariant());
                builder.Append(", ");
                builder.Append(validationMetadata is null
                    ? "null"
                    : SymbolDisplay.FormatLiteral(validationMetadata.Expression, true));
                builder.Append(", ");
                builder.Append(validationMetadata?.Message is null
                    ? "null"
                    : SymbolDisplay.FormatLiteral(validationMetadata.Message, true));
                builder.Append(", ");
                builder.Append(GetNamedBoolArgument(propertyAttribute, "LabelOnTop").ToString().ToLowerInvariant());
                builder.Append(", ");
                builder.Append(GetNamedStringLiteral(propertyAttribute, "DataTypeKey"));
                builder.AppendLine("),");
            }

            builder.Indent--;
            builder.Append("], ");
            builder.Append(BuildTypeSettings(contentTypeAttribute, definition, compilation, templateCompilation, definitionSymbols, context));
            builder.Append(", null, null, null, ");
            builder.Append(BuildCompositionAliases(definition));
            builder.Append(", ");
            builder.Append(BuildFolderPath(definition));
            builder.AppendLine("),");
            return;
        }

        var dataTypeAttribute = definition.GetAttributes().FirstOrDefault(
            attribute => IsAttribute(attribute, _dataTypeAttributeMetadataName));
        if (dataTypeAttribute is null) {
            return;
        }

        builder.Append("new global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinition(");
        builder.Append("global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinitionKind.DataType, ");
        builder.Append(
            SymbolDisplay.FormatLiteral(GetAliasArgument(dataTypeAttribute, GetNameArgument(dataTypeAttribute)), true));
        builder.Append(", ");
        builder.Append(
            SymbolDisplay.FormatLiteral(GetNameArgument(dataTypeAttribute), true));
        builder.Append(", ");
        builder.Append(
            SymbolDisplay.FormatLiteral(GetDataTypeEditorArgument(dataTypeAttribute), true));
        builder.Append(
            ", global::System.Array.Empty<global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstPropertyDefinition>(), null, null, ");
        builder.Append(GetConfigurationJsonLiteral(dataTypeAttribute, context));
        builder.Append(", ");
        builder.Append(GetDataTypeEditorUiArgument(dataTypeAttribute));
        builder.Append(", null, ");
        builder.Append(BuildFolderPath(definition));
        builder.Append(", ");
        builder.Append(BuildEditorConfiguration(dataTypeAttribute, context));
        builder.AppendLine("),");
    }

    private static string BuildTypeSettings(
        AttributeData attribute,
        INamedTypeSymbol definition,
        Compilation compilation,
        Compilation templateCompilation,
        ImmutableArray<INamedTypeSymbol> definitions,
        SourceProductionContext context) {
        var templateAttribute = ReferenceEquals(compilation, templateCompilation)
            ? attribute
            : GetReboundAttribute(attribute, templateCompilation);
        var allowedTemplates = BuildStringArray(templateAttribute, "AllowedTemplateAliases");
        var allowedChildren = BuildAllowedChildren(attribute, definition, compilation, definitions, context);
        var descriptionAttribute = FindAttribute(definition, _descriptionAttributeMetadataName);
        return $$"""
            new global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstTypeSettings(
                {{GetConstructorStringLiteral(descriptionAttribute)}},
                {{GetNamedStringLiteral(attribute, "Icon")}},
                {{IsAttribute(attribute, _elementTypeAttributeMetadataName).ToString().ToLowerInvariant()}},
                {{GetNamedBoolArgument(attribute, "AllowAsRoot").ToString().ToLowerInvariant()}},
                {{GetNamedBoolArgument(attribute, "AllowInLibrary").ToString().ToLowerInvariant()}},
                {{GetNamedStringLiteral(templateAttribute, "DefaultTemplateAlias")}},
                {{allowedTemplates}},
                {{allowedChildren}},
                {{GetNamedStringLiteral(attribute, "Variations")}},
                {{BuildCollectionSettings(definition, attribute, context)}})
            """;
    }

    private static AttributeData GetReboundAttribute(AttributeData attribute, Compilation compilation) {
        if(attribute.ApplicationSyntaxReference?.GetSyntax() is not AttributeSyntax syntax) {
            return attribute;
        }

        var model = compilation.GetSemanticModel(syntax.SyntaxTree);
        ISymbol? symbol = syntax.FirstAncestorOrSelf<PropertyDeclarationSyntax>() is { } property
            ? model.GetDeclaredSymbol(property)
            : syntax.FirstAncestorOrSelf<ClassDeclarationSyntax>() is { } declaration
                ? model.GetDeclaredSymbol(declaration)
                : null;
        return symbol?.GetAttributes().FirstOrDefault(candidate =>
            candidate.ApplicationSyntaxReference?.SyntaxTree == syntax.SyntaxTree
            && candidate.ApplicationSyntaxReference.Span == syntax.Span) ?? attribute;
    }

    private static string BuildCollectionSettings(
        INamedTypeSymbol definition, AttributeData typeAttribute, SourceProductionContext context) {
        var collection = FindAttribute(definition, _collectionAttributeMetadataName);
        if(collection is null) {
            return "null";
        }

        var configurationType = collection.ConstructorArguments.FirstOrDefault().Value as INamedTypeSymbol;
        var validBase = false;
        for(var current = configurationType?.BaseType; current is not null; current = current.BaseType) {
            if(current.ToDisplayString() == "Shorthand.UmbracoCodeFirst.Metadata.CodeFirstCollectionConfiguration") {
                validBase = true;
                break;
            }
        }

        if(configurationType is null || configurationType.IsAbstract || !validBase
            || !configurationType.InstanceConstructors.Any(constructor =>
                constructor.Parameters.Length == 0 && constructor.DeclaredAccessibility == Accessibility.Public)
            || (!IsAttribute(typeAttribute, _documentTypeAttributeMetadataName)
                && !IsAttribute(typeAttribute, _mediaTypeAttributeMetadataName))) {
            context.ReportDiagnostic(Diagnostic.Create(
                _invalidCollectionConfiguration,
                collection.ApplicationSyntaxReference?.GetSyntax().GetLocation(),
                definition.ToDisplayString()));
            return "null";
        }

        var kind = IsAttribute(typeAttribute, _mediaTypeAttributeMetadataName) ? "MediaType" : "DocumentType";
        return $"global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstCollectionConfiguration.FromType(typeof({configurationType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}), global::Shorthand.UmbracoCodeFirst.Metadata.CodeFirstDefinitionKind.{kind})";
    }

    private static string BuildCompositionAliases(INamedTypeSymbol definition) {
        var aliases = definition.GetAttributes()
            .Where(attribute => IsAttribute(attribute, _compositeAttributeMetadataName))
            .Select(attribute => attribute.ConstructorArguments.FirstOrDefault())
            .Where(argument => argument.Kind == TypedConstantKind.Type
                               && argument.Value is INamedTypeSymbol)
            .Select(argument => {
                var target = (INamedTypeSymbol)argument.Value!;
                var contentTypeAttribute = FindDocumentTypeAttribute(target);
                var targetName = contentTypeAttribute is null
                    ? target.Name
                    : GetNameArgument(contentTypeAttribute);
                return contentTypeAttribute is null
                    ? ToAlias(targetName)
                    : GetAliasArgument(contentTypeAttribute, targetName);
            })
            .Distinct(StringComparer.Ordinal)
            .OrderBy(alias => alias, StringComparer.Ordinal)
            .ToArray();

        if (aliases.Length == 0) {
            return "global::System.Array.Empty<string>()";
        }

        return $"new global::System.String[] {{ {string.Join(", ", aliases.Select(alias => SymbolDisplay.FormatLiteral(alias, true)))} }}";
    }

    private static string BuildFolderPath(INamedTypeSymbol definition) {
        var attribute = FindAttribute(definition, _folderPathAttributeMetadataName);
        return attribute is null || attribute.ConstructorArguments.Length == 0
            ? "null"
            : SymbolDisplay.FormatLiteral(
                attribute.ConstructorArguments[0].Value?.ToString() ?? string.Empty,
                true);
    }

    private static string BuildStringArray(AttributeData attribute, string name) {
        var value = attribute.NamedArguments.FirstOrDefault(argument => argument.Key == name).Value;
        if(value.Kind != TypedConstantKind.Array) {
            return "global::System.Array.Empty<string>()";
        }

        var values = string.Join(", ", value.Values.Select(item => SymbolDisplay.FormatLiteral(item.Value?.ToString() ?? string.Empty, true)));
        return $"new global::System.String[] {{ {values} }}";
    }

    private static string BuildAllowedChildren(
        AttributeData attribute,
        INamedTypeSymbol definition,
        Compilation compilation,
        ImmutableArray<INamedTypeSymbol> definitions,
        SourceProductionContext context) {
        var syntax = attribute.ApplicationSyntaxReference?.GetSyntax() as AttributeSyntax;
        var argument = syntax?.ArgumentList?.Arguments.FirstOrDefault(argument =>
            argument.NameEquals?.Name.Identifier.ValueText == "AllowedChildAliases");
        if(argument is null) {
            return BuildStringArray(attribute, "AllowedChildAliases");
        }

        var value = attribute.NamedArguments.FirstOrDefault(argument => argument.Key == "AllowedChildAliases").Value;
        if(value.Kind == TypedConstantKind.Array && value.IsNull) {
            return "global::System.Array.Empty<string>()";
        }

        if(value.Kind == TypedConstantKind.Array
            && value.Values.All(item => item.Kind != TypedConstantKind.Error)) {
            return BuildStringArray(attribute, "AllowedChildAliases");
        }

        var arrayExpression = argument.Expression;
        while(arrayExpression is ParenthesizedExpressionSyntax parenthesizedArray) {
            arrayExpression = parenthesizedArray.Expression;
        }

        var expressions = arrayExpression switch {
            ArrayCreationExpressionSyntax { Initializer: { } initializer } => initializer.Expressions.ToArray(),
            ImplicitArrayCreationExpressionSyntax array => array.Initializer.Expressions.ToArray(),
            _ => null,
        };
        if(expressions is null) {
            context.ReportDiagnostic(Diagnostic.Create(
                _unresolvedAllowedChild, argument.Expression.GetLocation(), argument.Expression.ToString(), definition.Name));
            return "global::System.Array.Empty<string>()";
        }

        var semanticModel = compilation.GetSemanticModel(argument.SyntaxTree);
        var aliases = new List<string>();
        foreach(var expression in expressions) {
            var constant = semanticModel.GetConstantValue(expression);
            if(constant.HasValue) {
                aliases.Add(constant.Value?.ToString() ?? string.Empty);
                continue;
            }

            var reference = expression;
            while(reference is ParenthesizedExpressionSyntax parenthesized) {
                reference = parenthesized.Expression;
            }

            if(reference is MemberAccessExpressionSyntax member
                && member.Name.Identifier.ValueText == "ModelTypeAlias"
                && semanticModel.GetSymbolInfo(member.Expression).Symbol is INamedTypeSymbol child
                && definitions.Any(candidate => SymbolEqualityComparer.Default.Equals(candidate, child))
                && FindDocumentTypeAttribute(child) is { } childAttribute) {
                aliases.Add(GetAliasArgument(childAttribute, GetNameArgument(childAttribute)));
                continue;
            }

            context.ReportDiagnostic(Diagnostic.Create(
                _unresolvedAllowedChild, expression.GetLocation(), expression.ToString(), definition.Name));
        }

        return $"new global::System.String[] {{ {string.Join(", ", aliases.Select(alias => SymbolDisplay.FormatLiteral(alias, true)))} }}";
    }
